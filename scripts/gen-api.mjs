// Writes docs/api.md from Eden's OpenAPI document, so the reference can't drift from the server.
//   node scripts/gen-api.mjs                     (fetches https://edenfamily.xyz/api/openapi.json)
//   node scripts/gen-api.mjs path/to/openapi.json
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = process.argv[2];
const spec = src ? JSON.parse(readFileSync(src, "utf8")) : await (await fetch("https://edenfamily.xyz/api/openapi.json")).json();
const BASE = "https://edenfamily.xyz/api";

const ops = [];
for (const [path, methods] of Object.entries(spec.paths)) {
  for (const [method, o] of Object.entries(methods)) {
    if (!["get", "post", "put", "patch", "delete"].includes(method)) continue;
    const json = o.requestBody?.content?.["application/json"];
    const ok = o.responses?.["200"]?.content ?? o.responses?.["101"]?.content ?? {};
    ops.push({ method: method.toUpperCase(), path, ...o, body: json?.example, bodySchema: json?.schema,
      example: Object.values(ok).find((c) => c.example !== undefined)?.example });
  }
}

const GROUPS = [
  ["Tokens", (o) => (o.path.startsWith("/tokens") && !/\/(quote|trades|candles)$/.test(o.path)) || o.path.startsWith("/token/") || o.path.startsWith("/images/")],
  ["Quotes & transactions", (o) => o.path.endsWith("/quote") || o.path.startsWith("/tx/") || o.path === "/uploads/image"],
  ["Charts & trades", (o) => /\/(trades|candles)$/.test(o.path) && o.path.startsWith("/tokens")],
  ["Wallets", (o) => o.path.startsWith("/wallets")],
  ["Creators & referrals", (o) => o.path.startsWith("/creators") || o.path.startsWith("/referrals")],
  ["Live feed", (o) => o.path === "/ws"],
  ["Status", () => true],
];

const sample = (p) => p.schema?.enum?.[0] ?? (p.schema?.default !== undefined ? String(p.schema.default)
  : /address/i.test(p.name) || p.schema?.pattern?.includes("40") ? "$TOKEN" : p.name === "amount" ? "1000000000000000000" : `<${p.name}>`);
function curl(o) {
  if (o.path === "/ws") return "wscat -c wss://edenfamily.xyz/ws";
  const path = o.path.replace(/\{(\w+)\}/g, (_, n) => { const p = (o.parameters ?? []).find((x) => x.name === n); return p ? sample(p) : `<${n}>`; });
  const q = (o.parameters ?? []).filter((p) => p.in === "query" && p.required).map((p) => `${p.name}=${sample(p)}`).join("&");
  const url = `${BASE}${path}${q ? `?${q}` : ""}`;
  if (o.method === "GET") return `curl "${url}"`;
  if (o.path === "/uploads/image") return `curl -X POST "${url}" \\\n  -H "content-type: image/png" --data-binary @logo.png`;
  return `curl -X ${o.method} "${url}" \\\n  -H "content-type: application/json" \\\n  -d '${JSON.stringify(o.body ?? {})}'`;
}
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
// GitHub heading anchors: lowercase, drop punctuation (keeping - and _), spaces become dashes
const anchor = (o) => `${o.method} ${o.path}`.toLowerCase().replace(/[^a-z0-9 _-]/g, "").replace(/ /g, "-");

let out = `# API

<!-- Generated by scripts/gen-api.mjs from ${src ? "openapi.json" : "https://edenfamily.xyz/api/openapi.json"} (Eden public API ${spec.info?.version ?? ""}). Do not edit by hand. -->

${spec.info?.description ?? ""}

Base URL: \`${BASE}\`. No API keys. The machine-readable spec is [\`/api/openapi.json\`](${BASE}/openapi.json).

## Trading through the API

1. **Quote.** \`GET /tokens/{address}/quote?side=buy&amount=<wei>&slippageBps=300\` returns \`expectedOut\` and \`minOut\`.
2. **Build.** \`POST /tx/swap\` with \`{ token, side, amount, user, slippageBps }\` returns the unsigned transactions to sign in order. A sell that needs an allowance gets its approval transactions first.
3. **Verify every transaction before signing:**
   - \`chainId\` is \`99901\`;
   - \`to\` is a published Eden or Uniswap address from [contracts](contracts.md), or the token or its curve;
   - the calldata decodes with the [ABIs](../abi/) (the Universal Router's \`execute\` for pool trades, see [trade](trade.md)) and ends with Eden's marker \`4544454e0001\`;
   - the minimum out in the calldata equals the quote's \`minOut\`, and the amount in is the amount you asked for.
4. **Sign locally.** Your key never leaves your machine; the API never asks for it.
5. **Send.** Broadcast the signed transaction yourself, or \`POST /tx/send\` with \`{ signedTransaction }\`. Read the receipt; a reverted trade costs only gas.

\`/tx/send\` only relays Eden contract calls of the kind the API builds. \`POST /tx/launch\` and \`POST /tx/claim\` follow the same build → verify → sign → send flow.

## Operations

`;
const left = [...ops];
const groups = GROUPS.map(([name, match]) => { const mine = left.filter(match); mine.forEach((o) => left.splice(left.indexOf(o), 1)); return [name, mine]; }).filter(([, m]) => m.length);
for (const [name, mine] of groups) {
  out += `**${name}**\n\n| | |\n|---|---|\n`;
  for (const o of mine) out += `| [\`${o.method} ${o.path}\`](#${anchor(o)}) | ${cell(o.summary)} |\n`;
  out += "\n";
}
for (const [name, mine] of groups) {
  out += `## ${name}\n\n`;
  for (const o of mine) {
    out += `### ${o.method} ${o.path}\n\n${o.summary ? `**${o.summary}.** ` : ""}${o.description ?? ""}\n\n`;
    const params = (o.parameters ?? []).filter((p) => p.in !== "header");
    if (params.length) {
      out += "| Parameter | In | Required | Description |\n|---|---|---|---|\n";
      for (const p of params) out += `| \`${p.name}\` | ${p.in} | ${p.required ? "yes" : ""} | ${cell(p.description)}${p.schema?.enum ? ` One of \`${p.schema.enum.join("`, `")}\`.` : ""}${p.schema?.default !== undefined ? ` Default \`${p.schema.default}\`.` : ""} |\n`;
      out += "\n";
    }
    const props = Object.entries(o.bodySchema?.properties ?? {});
    if (props.length) {
      out += "| Body field | Required | Description |\n|---|---|---|\n";
      for (const [k, v] of props) out += `| \`${k}\` | ${(o.bodySchema.required ?? []).includes(k) ? "yes" : ""} | ${cell(v.description ?? v.type)} |\n`;
      out += "\n";
    }
    out += "```bash\n" + curl(o) + "\n```\n\n";
    if (o.example !== undefined) out += "<details><summary>Example response</summary>\n\n```json\n" + (typeof o.example === "string" ? o.example : JSON.stringify(o.example, null, 2)) + "\n```\n\n</details>\n\n";
  }
}
writeFileSync(join(root, "docs/api.md"), out);
console.log(`docs/api.md: ${ops.length} operations`);
